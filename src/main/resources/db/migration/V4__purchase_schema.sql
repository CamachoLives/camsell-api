-- Flujo de compra: ofertas del comprador y publicaciones guardadas.
CREATE TABLE purchase_offer (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id        BIGINT        NOT NULL,
    listing_reference VARCHAR(20)   NOT NULL,
    listing_title     VARCHAR(200)  NOT NULL,
    seller_id         BIGINT        NOT NULL,
    buyer_id          BIGINT        NOT NULL,
    buyer_name        VARCHAR(160)  NOT NULL,
    buyer_phone       VARCHAR(40),
    amount            NUMERIC(16,2) NOT NULL,
    currency          VARCHAR(3)    NOT NULL,
    message           VARCHAR(1000),
    status            VARCHAR(20)   NOT NULL,
    responded_at      TIMESTAMP(6) WITH TIME ZONE,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_offer_listing FOREIGN KEY (listing_id) REFERENCES listing (id) ON DELETE CASCADE,
    CONSTRAINT fk_offer_seller FOREIGN KEY (seller_id) REFERENCES app_user (id),
    CONSTRAINT fk_offer_buyer FOREIGN KEY (buyer_id) REFERENCES app_user (id)
);

CREATE INDEX ix_offer_seller_status ON purchase_offer (seller_id, status);
CREATE INDEX ix_offer_buyer ON purchase_offer (buyer_id);
CREATE INDEX ix_offer_listing ON purchase_offer (listing_id);

CREATE TABLE favorite_listing (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    listing_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_favorite_user_listing UNIQUE (user_id, listing_id),
    CONSTRAINT fk_favorite_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_favorite_listing FOREIGN KEY (listing_id) REFERENCES listing (id) ON DELETE CASCADE
);
