-- Catalogo de parametros: el nucleo que hace configurable la plataforma.
CREATE TABLE parameter_group (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR(40)  NOT NULL,
    name                 VARCHAR(120) NOT NULL,
    description          VARCHAR(400),
    data_type            VARCHAR(20)  NOT NULL,
    scope                VARCHAR(20)  NOT NULL DEFAULT 'LISTING',
    multi_valued         BOOLEAN      NOT NULL DEFAULT FALSE,
    filterable           BOOLEAN      NOT NULL DEFAULT TRUE,
    required_for_listing BOOLEAN      NOT NULL DEFAULT FALSE,
    show_in_specs        BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order           INTEGER      NOT NULL DEFAULT 100,
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_parameter_group_code UNIQUE (code)
);

CREATE TABLE parameter_option (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_code VARCHAR(40)  NOT NULL,
    code       VARCHAR(60)  NOT NULL,
    label      VARCHAR(120) NOT NULL,
    icon_name  VARCHAR(60),
    color_hex  VARCHAR(9),
    sort_order INTEGER      NOT NULL DEFAULT 100,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_parameter_option UNIQUE (group_code, code),
    CONSTRAINT fk_parameter_option_group FOREIGN KEY (group_code)
        REFERENCES parameter_group (code) ON DELETE CASCADE
);

CREATE INDEX ix_parameter_option_group ON parameter_option (group_code, sort_order);

-- Arbol marca / modelo, administrable desde la consola.
CREATE TABLE brand (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(80)  NOT NULL,
    slug              VARCHAR(100) NOT NULL,
    country_of_origin VARCHAR(80),
    logo_url          VARCHAR(400),
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_brand_name UNIQUE (name),
    CONSTRAINT uk_brand_slug UNIQUE (slug)
);

CREATE TABLE vehicle_model (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id       BIGINT       NOT NULL,
    name           VARCHAR(80)  NOT NULL,
    slug           VARCHAR(160) NOT NULL,
    body_type_code VARCHAR(60),
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_vehicle_model_slug UNIQUE (slug),
    CONSTRAINT uk_vehicle_model_brand_name UNIQUE (brand_id, name),
    CONSTRAINT fk_vehicle_model_brand FOREIGN KEY (brand_id)
        REFERENCES brand (id) ON DELETE CASCADE
);

CREATE INDEX ix_vehicle_model_brand ON vehicle_model (brand_id);
