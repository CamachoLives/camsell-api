-- Publicaciones de venta de vehiculos.
CREATE TABLE listing (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference      VARCHAR(20)   NOT NULL,
    slug           VARCHAR(220)  NOT NULL,
    seller_id      BIGINT        NOT NULL,
    seller_name    VARCHAR(160)  NOT NULL,
    brand_id       BIGINT        NOT NULL,
    brand_name     VARCHAR(80)   NOT NULL,
    model_id       BIGINT        NOT NULL,
    model_name     VARCHAR(80)   NOT NULL,
    title          VARCHAR(200)  NOT NULL,
    model_year     INTEGER       NOT NULL,
    mileage_km     INTEGER       NOT NULL,
    price_amount   NUMERIC(16,2) NOT NULL,
    price_currency VARCHAR(3)    NOT NULL,
    negotiable     BOOLEAN       NOT NULL DEFAULT FALSE,
    description    VARCHAR(6000) NOT NULL,
    city_code      VARCHAR(60),
    status         VARCHAR(20)   NOT NULL,
    featured       BOOLEAN       NOT NULL DEFAULT FALSE,
    view_count     BIGINT        NOT NULL DEFAULT 0,
    published_at   TIMESTAMP(6) WITH TIME ZONE,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_listing_reference UNIQUE (reference),
    CONSTRAINT uk_listing_slug UNIQUE (slug),
    CONSTRAINT fk_listing_seller FOREIGN KEY (seller_id) REFERENCES app_user (id),
    CONSTRAINT fk_listing_brand FOREIGN KEY (brand_id) REFERENCES brand (id),
    CONSTRAINT fk_listing_model FOREIGN KEY (model_id) REFERENCES vehicle_model (id)
);

CREATE INDEX ix_listing_status_published ON listing (status, published_at);
CREATE INDEX ix_listing_brand_model ON listing (brand_id, model_id);
CREATE INDEX ix_listing_price ON listing (price_amount);
CREATE INDEX ix_listing_seller ON listing (seller_id);
CREATE INDEX ix_listing_featured ON listing (featured, status);

CREATE TABLE listing_image (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id    BIGINT       NOT NULL,
    url           VARCHAR(500) NOT NULL,
    alt_text      VARCHAR(200),
    sort_position INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT fk_listing_image_listing FOREIGN KEY (listing_id)
        REFERENCES listing (id) ON DELETE CASCADE
);

CREATE INDEX ix_listing_image_listing ON listing_image (listing_id, sort_position);

-- Valores de parametros por publicacion: permite agregar especificaciones
-- nuevas sin alterar la tabla listing.
CREATE TABLE listing_attribute (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id   BIGINT      NOT NULL,
    group_code   VARCHAR(40) NOT NULL,
    option_code  VARCHAR(60),
    text_value   VARCHAR(500),
    number_value NUMERIC(16,2),
    bool_value   BOOLEAN,
    CONSTRAINT fk_listing_attribute_listing FOREIGN KEY (listing_id)
        REFERENCES listing (id) ON DELETE CASCADE
);

CREATE INDEX ix_listing_attribute_filter ON listing_attribute (group_code, option_code);
CREATE INDEX ix_listing_attribute_listing ON listing_attribute (listing_id);
