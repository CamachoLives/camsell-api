-- Seccion informativa: notas editoriales del portal.
CREATE TABLE news_article (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug            VARCHAR(220)   NOT NULL,
    title           VARCHAR(200)   NOT NULL,
    excerpt         VARCHAR(500),
    body            VARCHAR(20000) NOT NULL,
    cover_image_url VARCHAR(500),
    category_code   VARCHAR(60),
    author_id       BIGINT         NOT NULL,
    author_name     VARCHAR(160)   NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    featured        BOOLEAN        NOT NULL DEFAULT FALSE,
    reading_minutes INTEGER        NOT NULL DEFAULT 1,
    view_count      BIGINT         NOT NULL DEFAULT 0,
    published_at    TIMESTAMP(6) WITH TIME ZONE,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_news_article_slug UNIQUE (slug),
    CONSTRAINT fk_news_article_author FOREIGN KEY (author_id) REFERENCES app_user (id)
);

CREATE INDEX ix_news_article_status ON news_article (status, published_at);
CREATE INDEX ix_news_article_category ON news_article (category_code);

CREATE TABLE news_article_tag (
    article_id BIGINT      NOT NULL,
    tag        VARCHAR(60) NOT NULL,
    CONSTRAINT pk_news_article_tag PRIMARY KEY (article_id, tag),
    CONSTRAINT fk_news_article_tag_article FOREIGN KEY (article_id)
        REFERENCES news_article (id) ON DELETE CASCADE
);
